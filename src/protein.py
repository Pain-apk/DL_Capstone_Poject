UNICODE_FRACTIONS = {
    "½": 0.5, "⅓": 1/3, "⅔": 2/3, "¼": 0.25, "¾": 0.75,
    "⅕": 0.2, "⅖": 0.4, "⅗": 0.6, "⅘": 0.8, "⅙": 1/6,
    "⅚": 5/6, "⅛": 0.125, "⅜": 0.375, "⅝": 0.625, "⅞": 0.875
}

class UnitConverter:
    def __init__(self, conversion_csv: str = "data/raw/unit_conversions.csv"):
        self.conversions: Dict[Tuple[str, str], float] = {}
        self.default_conversions: Dict[str, float] = {}
        if os.path.exists(conversion_csv):
            with open(conversion_csv, mode="r", encoding="utf-8") as f:
                reader = csv.DictReader(f)
                for row in reader:
                    ing = row["ingredient"].strip().lower()
                    unit = row["unit"].strip().lower()
                    try:
                        grams = float(row["grams"])
                    except (ValueError, KeyError):
                        continue
                    if ing == "default":
                        self.default_conversions[unit] = grams
                    else:
                        self.conversions[(ing, unit)] = grams

    def get_grams(self, ingredient_name: str, unit: str, quantity: float) -> float:
        ing_clean = ingredient_name.strip().lower()
        unit_clean = unit.strip().lower()

        # Direct (ingredient, unit) match
        if (ing_clean, unit_clean) in self.conversions:
            return quantity * self.conversions[(ing_clean, unit_clean)]

        # Partial match on ingredient
        for (k_ing, k_unit), g in self.conversions.items():
            if k_unit == unit_clean and k_ing in ing_clean:
                return quantity * g

        # Fallback to default unit grams
        if unit_clean in self.default_conversions:
            return quantity * self.default_conversions[unit_clean]

        # Unknown unit: fallback 100g per piece/unit or quantity directly if grams
        if "gram" in unit_clean or unit_clean == "g":
            return quantity
        if "kg" in unit_clean:
            return quantity * 1000.0
        return quantity * 50.0  # conservative generic default


def clean_unicode_text(text: str) -> str:
    res = text
    for char, val in UNICODE_FRACTIONS.items():
        res = res.replace(char, f" {val} ")
    return res


def parse_quantity_unit(raw_str: str) -> Tuple[float, str, str]:
    """
    Parses phrases like:
    '1 cup thick poha' -> (1.0, 'cup', 'poha')
    '1/2 tsp turmeric' -> (0.5, 'tsp', 'turmeric')
    '2 medium onion' -> (2.0, 'medium', 'onion')
    'salt to taste' -> (1.0, 'pinch', 'salt')
    """
    clean_str = clean_unicode_text(raw_str).strip()
    if "to taste" in clean_str.lower():
        name = clean_str.lower().replace("to taste", "").strip()
        return 1.0, "pinch", name

    # Match fraction or decimal: e.g. "1 1/2" or "1/2" or "2.5" or "2"
    pattern = r"^(\d+\s+\d+/\d+|\d+/\d+|\d+\.\d+|\d+)\s*([a-zA-Z]+)?\s*(.*)$"
    m = re.match(pattern, clean_str)
    if not m:
        # No leading number, treat as 1 piece / item
        return 1.0, "piece", clean_str

    qty_str, unit_candidate, rest = m.groups()
    qty = 0.0
    if "/" in qty_str:
        parts = qty_str.split()
        if len(parts) == 2:
            whole, frac = parts
            n, d = frac.split("/")
            qty = float(whole) + (float(n) / float(d))
        else:
            n, d = parts[0].split("/")
            qty = float(n) / float(d)
    else:
        try:
            qty = float(qty_str)
        except ValueError:
            qty = 1.0

    known_units = {
        "cup", "cups", "tbsp", "tablespoon", "tablespoons",
        "tsp", "teaspoon", "teaspoons", "piece", "pieces",
        "pinch", "pinches", "clove", "cloves", "inch", "inches",
        "g", "gram", "grams", "kg", "ml", "liter", "litres",
        "small", "medium", "large"
    }

    unit = "piece"
    item_name = rest.strip() if rest else ""
    if unit_candidate:
        uc_lower = unit_candidate.lower()
        if uc_lower in known_units:
            unit = uc_lower
        else:
            item_name = f"{unit_candidate} {item_name}".strip()

    # Standardize plural units
    unit_map = {
        "cups": "cup", "tablespoons": "tbsp", "tablespoon": "tbsp",
        "teaspoons": "tsp", "teaspoon": "tsp", "pieces": "piece",
        "pinches": "pinch", "cloves": "clove", "inches": "inch",
        "grams": "g", "gram": "g"
    }
    unit = unit_map.get(unit, unit)
    return qty, unit, item_name.strip()


class ProteinCalculator:
    def __init__(self,
                 synonyms_path: str = "src/ingredient_synonyms.json",
                 conversions_path: str = "data/raw/unit_conversions.csv"):
        self.nutrition_db = get_nutrition_db()
        self.unit_converter = UnitConverter(conversions_path)
        self.synonyms: Dict[str, str] = {}
        if os.path.exists(synonyms_path):
            with open(synonyms_path, "r", encoding="utf-8") as f:
                self.synonyms = json.load(f)

    def normalize_name(self, raw_name: str) -> str:
        name = raw_name.lower().strip()
        # Direct synonym lookup
        if name in self.synonyms:
            return self.synonyms[name]
        # Token match
        for syn, target in self.synonyms.items():
            if syn in name:
                return target
        return name

    def compute_recipe_protein(self,
                               ingredients_with_qty: List[str],
                               main_ingredients: List[str],
                               servings: float = 2.0) -> Tuple[float, str, List[Dict[str, Any]]]:
        """
        Calculates:
        protein_g_per_serving = sum(grams * protein_per_100g / 100) / servings
        protein_confidence = 'high' only if all main ingredients were matched, else 'low'
        """
        total_protein_g = 0.0
        item_breakdown = []
        matched_main_set = set()

        for line in ingredients_with_qty:
            qty, unit, raw_item = parse_quantity_unit(line)
            norm_name = self.normalize_name(raw_item)
            grams = self.unit_converter.get_grams(norm_name, unit, qty)
            nutrition_entry = self.nutrition_db.get_protein_per_100g(norm_name)

            prot_per_100g = 0.0
            src = "unmatched"
            if nutrition_entry:
                prot_per_100g, src = nutrition_entry

            item_protein = (grams * prot_per_100g) / 100.0
            total_protein_g += item_protein

            item_breakdown.append({
                "raw": line,
                "parsed_name": norm_name,
                "quantity": qty,
                "unit": unit,
                "grams": round(grams, 2),
                "protein_per_100g": prot_per_100g,
                "source": src,
                "item_protein_g": round(item_protein, 2)
            })

            # Check if this satisfies any main ingredient
            for main_ing in main_ingredients:
                norm_main = self.normalize_name(main_ing)
                if norm_main in norm_name or norm_name in norm_main:
                    if nutrition_entry is not None:
                        matched_main_set.add(norm_main)

        clean_servings = max(1.0, float(servings))
        protein_per_serving = total_protein_g / clean_servings

        # Confidence: 'high' only if all main ingredients matched
        clean_main_norm = {self.normalize_name(m) for m in main_ingredients if m.strip()}
        all_main_matched = clean_main_norm.issubset(matched_main_set) if clean_main_norm else False
        confidence = "high" if all_main_matched else "low"

        return round(protein_per_serving, 2), confidence, item_breakdown


def sanity_test_besan() -> bool:
    """
    Sanity test: besan should be about 22 g per 100 g dry.
    Reports any failure.
    """
    calc = ProteinCalculator()
    prot_info = calc.nutrition_db.get_protein_per_100g("besan")
    if not prot_info:
        print("[FAIL] Sanity test: 'besan' not found in protein database!")
        return False
    prot_val, src = prot_info
    print(f"[SANITY TEST] Besan dry protein per 100g: {prot_val}g (Source: {src})")
    if 21.0 <= prot_val <= 23.5:
        print("[PASS] Besan dry protein is ~22g per 100g.")
        return True
    else:
        print(f"[FAIL] Besan protein {prot_val}g outside expected range [21.0, 23.5]g")
        return False


if __name__ == "__main__":
    passed = sanity_test_besan()
    if not passed:
        exit(1)
