def build_catalog():
    os.makedirs(os.path.dirname(OUTPUT_CSV), exist_ok=True)
    all_rows = []

    # Process Tier 1: Maharashtra
    for dish_name, local_name, diet, pan_india in MAHARASHTRA_DISHES:
        s1, s2, s3 = make_sources(dish_name, "Maharashtrian")
        all_rows.append({
            "dish_name": dish_name,
            "local_name": local_name,
            "state": "Maharashtra",
            "tier": "Tier 1",
            "diet": diet,
            "pan_india": pan_india,
            "source_1": s1,
            "source_2": s2,
            "source_3": s3,
            "verified": "no",
            "review_flag": "pending"
        })

    # Process Tier 2: Neighbours
    for state, dishes in TIER2_STATES.items():
        for dish_name, local_name, diet, pan_india in dishes:
            s1, s2, s3 = make_sources(dish_name, f"{state} Indian")
            all_rows.append({
                "dish_name": dish_name,
                "local_name": local_name,
                "state": state,
                "tier": "Tier 2",
                "diet": diet,
                "pan_india": pan_india,
                "source_1": s1,
                "source_2": s2,
                "source_3": s3,
                "verified": "no",
                "review_flag": "pending"
            })

    with open(OUTPUT_CSV, mode="w", newline="", encoding="utf-8") as f:
        fieldnames = [
            "dish_name", "local_name", "state", "tier", "diet",
            "pan_india", "source_1", "source_2", "source_3",
            "verified", "review_flag"
        ]
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(all_rows)

    print(f"Successfully generated {len(all_rows)} dishes into {OUTPUT_CSV}")
    tier1_cnt = sum(1 for r in all_rows if r["tier"] == "Tier 1")
    tier2_cnt = sum(1 for r in all_rows if r["tier"] == "Tier 2")
    print(f"Tier 1 (Maharashtra): {tier1_cnt} dishes")
    print(f"Tier 2 (Neighbours): {tier2_cnt} dishes")
    for st in TIER2_STATES:
        cnt = sum(1 for r in all_rows if r["state"] == st)
        print(f"  - {st}: {cnt} dishes")

if __name__ == "__main__":
    build_catalog()

