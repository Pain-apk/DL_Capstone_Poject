def make_sources(dish_name: str, cuisine: str):
    q = urllib.parse.quote_plus(f"{dish_name} recipe {cuisine}")
    s1 = f"https://www.tarladalal.com/recipes-for-{urllib.parse.quote_plus(dish_name.lower())}"
    s2 = f"https://hebbarskitchen.com/?s={urllib.parse.quote_plus(dish_name.lower())}"
    s3 = f"https://www.archanaskitchen.com/search?searchword={urllib.parse.quote_plus(dish_name.lower())}"
    return s1, s2, s3

